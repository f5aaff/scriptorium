package fao

import (
	"fmt"
	"io"
	"os"
	"path/filepath"
	"strings"
)

type FAO interface {
	SaveFile(path string, data io.Reader) error
	GetFile(path string) (io.ReadCloser, error)
	DeleteFile(path string) error
	FileExists(filename string) bool
}

// LocalFao stores library objects below one configured root directory.
// Callers must use storage-relative paths, never user-supplied absolute paths.
type LocalFao struct {
	basePath string
}

func NewLocalFao(basePath string) *LocalFao {
	abs, err := filepath.Abs(basePath)
	if err != nil {
		return &LocalFao{basePath: basePath}
	}
	return &LocalFao{basePath: filepath.Clean(abs)}
}

// resolve validates a storage-relative path and rejects traversal and symlinks
// in existing path components. Storage names are generated by the application.
func (l *LocalFao) resolve(name string, createParents bool) (string, error) {
	if name == "" || filepath.IsAbs(name) || !filepath.IsLocal(name) {
		return "", fmt.Errorf("invalid storage path %q", name)
	}
	clean := filepath.Clean(name)
	if clean == "." || strings.HasPrefix(clean, ".."+string(filepath.Separator)) {
		return "", fmt.Errorf("invalid storage path %q", name)
	}

	root := l.basePath
	if err := os.MkdirAll(root, 0700); err != nil {
		return "", fmt.Errorf("create storage root: %w", err)
	}
	current := root
	parts := strings.Split(clean, string(filepath.Separator))
	for i, part := range parts {
		current = filepath.Join(current, part)
		info, err := os.Lstat(current)
		if err != nil {
			if !os.IsNotExist(err) {
				return "", fmt.Errorf("inspect storage path: %w", err)
			}
			if createParents && i < len(parts)-1 {
				if err := os.Mkdir(current, 0700); err != nil && !os.IsExist(err) {
					return "", fmt.Errorf("create storage directory: %w", err)
				}
				continue
			}
			continue
		}
		if info.Mode()&os.ModeSymlink != 0 {
			return "", fmt.Errorf("storage path must not traverse symlinks")
		}
		if i < len(parts)-1 && !info.IsDir() {
			return "", fmt.Errorf("storage path component is not a directory")
		}
	}
	return current, nil
}

func (l *LocalFao) SaveFile(name string, data io.Reader) error {
	path, err := l.resolve(name, true)
	if err != nil {
		return err
	}
	file, err := os.OpenFile(path, os.O_WRONLY|os.O_CREATE|os.O_EXCL, 0600)
	if err != nil {
		return fmt.Errorf("create stored file: %w", err)
	}
	if _, err := io.Copy(file, data); err != nil {
		_ = file.Close()
		_ = os.Remove(path)
		return fmt.Errorf("write stored file: %w", err)
	}
	if err := file.Sync(); err != nil {
		_ = file.Close()
		_ = os.Remove(path)
		return fmt.Errorf("sync stored file: %w", err)
	}
	if err := file.Close(); err != nil {
		_ = os.Remove(path)
		return fmt.Errorf("close stored file: %w", err)
	}
	return nil
}

func (l *LocalFao) GetFile(name string) (io.ReadCloser, error) {
	path, err := l.resolve(name, false)
	if err != nil {
		return nil, err
	}
	file, err := os.Open(path)
	if err != nil {
		return nil, fmt.Errorf("open stored file: %w", err)
	}
	return file, nil
}

func (l *LocalFao) DeleteFile(name string) error {
	path, err := l.resolve(name, false)
	if err != nil {
		return err
	}
	if err := os.Remove(path); err != nil {
		return fmt.Errorf("delete stored file: %w", err)
	}
	return nil
}

func (l *LocalFao) FileExists(name string) bool {
	path, err := l.resolve(name, false)
	if err != nil {
		return false
	}
	info, err := os.Stat(path)
	return err == nil && info.Mode().IsRegular()
}
